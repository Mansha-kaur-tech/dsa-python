# ---------------------------------------------
# Loops in Python
# ---------------------------------------------

# ---------------------------------------------
# 1. For Loop
# ---------------------------------------------
word = "hello"
for i in word:
    print(i)  # Output: h, e, l, l, o

# ---------------------------------------------
# 2. range()
# ---------------------------------------------

for i in range(1, 6):
    print(i)  # Output: 1, 2, 3, 4, 5

# ---------------------------------------------
# 3. step values 
# ---------------------------------------------

for i in range(1,30,5):
    print(i)

for i in range(20,2,-1):      # Reverse loop
    print(i)

# ---------------------------------------------
# 4. while loop
# ---------------------------------------------

s = 10
while s > 5:
    print("HELLO")
    s = s-1

# ---------------------------------------------
# 5. break
# ---------------------------------------------

for i in range(10):
    if i == 5:
        break
    print(i)

# ---------------------------------------------
# 6. continue
# ---------------------------------------------

for i in range(10):
    if i == 5:
        continue
    print(i)

# --------------------------------------------
# 7. pass
# --------------------------------------------

for i in range(10):
    if i == 5:
        pass
    print(i)

# --------------------------------------------
# 8. Nested loops
# --------------------------------------------

for i in range(3):
    for letter in "World":
        print(letter)

# --------------------------------------------
# 9. loop else
# --------------------------------------------

for i in range(5):
    print(i)
else:
    print("Loop Finished!")


